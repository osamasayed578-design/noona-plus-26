def q(s):
    return (s or '').replace("'", "''")


def short(name, limit=128):
    if len(name) <= limit:
        return name
    h = hashlib.md5(name.encode()).hexdigest()[:6].upper()
    return name[:limit - 7] + '_' + h


# ---------------------------------------------------------------- resolve FKs
def resolve():
    errors = []
    for t in TABLES.values():
        t.fks = []
        for c in t.cols:
            if not c.fk:
                continue
            ptab, pcol = c.fk
            p = TABLES.get(ptab)
            if p is None:
                errors.append(f'{t.name}.{c.name} -> unknown table {ptab}')
                continue
            pc = p.col(pcol)
            if pc is None:
                errors.append(f'{t.name}.{c.name} -> unknown column {ptab}.{pcol}')
                continue
            if pcol != 'ID':
                if not any(u == (pcol,) for u in p.uks) and pcol != 'ID':
                    errors.append(f'{t.name}.{c.name} -> {ptab}.{pcol} is not single-column unique')
            composite = (t.scope in ('T', 'C') and p.scope in ('T', 'C') and pcol == 'ID'
                         and c.name != 'TENANT_ID')
            if composite:
                p.needs_tenant_uk = True
                t.fks.append(dict(cols=('TENANT_ID', c.name), ptab=ptab, pcols=('TENANT_ID', 'ID'),
                                  col=c.name, nullable=c.nullable))
            else:
                t.fks.append(dict(cols=(c.name,), ptab=ptab, pcols=(pcol,), col=c.name,
                                  nullable=c.nullable))
    for t in TABLES.values():
        if t.needs_tenant_uk and ('TENANT_ID', 'ID') not in t.uks:
            t.uks.insert(0, ('TENANT_ID', 'ID'))
        for u in t.uks + t.ixs + t.nuks:
            for cn in u:
                if not t.col(cn):
                    errors.append(f'{t.name}: key/index column {cn} not found')
    if errors:
        print('\n'.join(errors))
        sys.exit(1)


def fk_home(t, fk):
    """FK is emitted in the module file installed last among child & parent."""
    p = TABLES[fk['ptab']]
    return ORDER[max(MOD_IDX[t.module.code], MOD_IDX[p.module.code])]


# ---------------------------------------------------------------- DDL
def col_ddl(t, c):
    parts = [f'  {c.name:<32} {c.otype}']
    if c.name == 'ID':
        parts.append('GENERATED BY DEFAULT ON NULL AS IDENTITY')
    elif c.default is not None:
        parts.append(('DEFAULT ON NULL ' if not c.nullable else 'DEFAULT ') + c.default)
    if not c.nullable and c.name != 'ID':
        parts.append('NOT NULL')
    return ' '.join(parts)


def table_ddl(t):
    lines = [col_ddl(t, c) for c in t.cols]
    cons = [f'  CONSTRAINT {short(t.name + "_PK")} PRIMARY KEY (ID)']
    for i, u in enumerate(t.uks, 1):
        cons.append(f'  CONSTRAINT {short(f"{t.name}_UK{i}")} UNIQUE ({", ".join(u)})')
    for c in t.cols:
        if c.check_in:
            vals = ', '.join(f"'{v}'" for v in c.check_in)
            cons.append(f'  CONSTRAINT {short(f"{t.name}_{c.name}_CK")} CHECK ({c.name} IN ({vals}))')
        elif c.ltype == 'YN':
            cons.append(f"  CONSTRAINT {short(f'{t.name}_{c.name}_CK')} CHECK ({c.name} IN ('Y', 'N'))")
        elif c.ltype == 'JSON':
            cons.append(f'  CONSTRAINT {short(f"{t.name}_{c.name}_JS")} CHECK ({c.name} IS JSON)')
    for i, ch in enumerate(t.checks, 1):
        cons.append(f'  CONSTRAINT {short(f"{t.name}_CK{i}")} CHECK ({ch})')
    body = ',\n'.join(lines + cons)
    return f'CREATE TABLE {t.name} (\n{body}\n);\n'


# FKs to small, rarely-changing reference tables are not indexed (no random indexes - 46.1)
NO_FK_INDEX = {'REF_CURRENCY', 'REF_COUNTRY', 'REF_LANGUAGE', 'REF_ENTITY_TYPE', 'REF_CITY', 'REF_TIMEZONE'}


def index_ddl(t):
    covered = [('ID',)] + list(t.uks)
    out = []
    n = 0

    def is_covered(cols):
        return any(tuple(k[:len(cols)]) == tuple(cols) for k in covered)

    for fk in t.fks:
        if fk['cols'] == ('TENANT_ID',) and t.scope in ('T', 'C', 'TO'):
            cols = ('TENANT_ID',)
        else:
            cols = fk['cols']
        if is_covered(cols) or fk['ptab'] in NO_FK_INDEX:
            continue
        name = short(f'{t.name}_{fk["col"]}_IX')
        out.append(f'CREATE INDEX {name} ON {t.name} ({", ".join(cols)});')
        covered.append(cols)
    for i, u in enumerate(t.nuks, 1):
        last = u[-1]
        exprs = [f'CASE WHEN {last} IS NOT NULL THEN {c} END' for c in u[:-1]] + [last]
        out.append(f'CREATE UNIQUE INDEX {short(f"{t.name}_NUK{i}")} ON {t.name} ({", ".join(exprs)});')
    for ix in t.ixs:
        if is_covered(ix):
            continue
        n += 1
        out.append(f'CREATE INDEX {short(f"{t.name}_IX{n}")} ON {t.name} ({", ".join(ix)});')
        covered.append(ix)
    return out


def comments_ddl(t):
    tc = f'{t.ar} | {t.en}'
    if t.purpose:
        tc += f' | {t.purpose}'
    out = [f"COMMENT ON TABLE {t.name} IS '{q(tc)[:3900]}';"]
    for c in t.cols:
        d = c.desc
        if c.check_in:
            d += ' [' + ', '.join(c.check_in) + ']'
        out.append(f"COMMENT ON COLUMN {t.name}.{c.name} IS '{q(d)[:3900]}';")
    return out


def fk_ddl(t, fk):
    name = short(f'{t.name}_{fk["col"]}_FK')
    return (f'ALTER TABLE {t.name} ADD CONSTRAINT {name} FOREIGN KEY ({", ".join(fk["cols"])}) '
            f'REFERENCES {fk["ptab"]} ({", ".join(fk["pcols"])});')


def trigger_ddl(t):
    nm = short(f'{t.name}_BIU', 128)
    tenant_ins = ''
    tenant_upd = ''
    if t.has_tenant:
        tenant_ins = ("    IF :NEW.TENANT_ID IS NULL THEN\n"
                      "      :NEW.TENANT_ID := NOONA_CTX_PKG.TENANT_ID;\n"
                      "    END IF;\n")
        tenant_upd = ("    IF NOT ((:NEW.TENANT_ID = :OLD.TENANT_ID) OR (:NEW.TENANT_ID IS NULL AND :OLD.TENANT_ID IS NULL)) THEN\n"
                      "      RAISE_APPLICATION_ERROR(-20001, 'NOONA-SEC-001: TENANT_ID is immutable');\n"
                      "    END IF;\n")
    if t.append:
        return (f"CREATE OR REPLACE TRIGGER {nm}\n"
                f"BEFORE INSERT OR UPDATE OR DELETE ON {t.name}\nFOR EACH ROW\nBEGIN\n"
                f"  IF INSERTING THEN\n{tenant_ins}"
                f"    :NEW.CREATED_BY := COALESCE(:NEW.CREATED_BY, NOONA_CTX_PKG.CURRENT_USER_NAME);\n"
                f"    :NEW.CREATED_AT := SYSTIMESTAMP;\n"
                f"  ELSIF DELETING AND NOONA_CTX_PKG.PURGE_MODE = 'Y' THEN\n"
                f"    NULL; -- حذف مسموح فقط عبر إجراء الإتلاف المعتمد\n"
                f"  ELSE\n"
                f"    RAISE_APPLICATION_ERROR(-20002, 'NOONA-AUD-001: {t.name} is append-only');\n"
                f"  END IF;\nEND;\n/\n")
    return (f"CREATE OR REPLACE TRIGGER {nm}\n"
            f"BEFORE INSERT OR UPDATE ON {t.name}\nFOR EACH ROW\nBEGIN\n"
            f"  IF INSERTING THEN\n{tenant_ins}"
            f"    :NEW.CREATED_BY  := COALESCE(:NEW.CREATED_BY, NOONA_CTX_PKG.CURRENT_USER_NAME);\n"
            f"    :NEW.CREATED_AT  := SYSTIMESTAMP;\n"
            f"    :NEW.ROW_VERSION := 1;\n"
            f"  ELSE\n{tenant_upd}"
            f"    :NEW.CREATED_BY  := :OLD.CREATED_BY;\n"
            f"    :NEW.CREATED_AT  := :OLD.CREATED_AT;\n"
            f"    :NEW.ROW_VERSION := NVL(:OLD.ROW_VERSION, 0) + 1;\n"
            f"    :NEW.UPDATED_BY  := NOONA_CTX_PKG.CURRENT_USER_NAME;\n"
            f"    :NEW.UPDATED_AT  := SYSTIMESTAMP;\n"
            f"  END IF;\nEND;\n/\n")


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w', encoding='utf-8') as f:
        f.write(text)


def gen_ddl():
    fks_by_home = {m.code: [] for m in ORDER}
    for t in TABLES.values():
        for fk in t.fks:
            fks_by_home[fk_home(t, fk).code].append((t, fk))
    install = [HEADER.format(title='DDL install order (tables, constraints, indexes, comments)'),
               'SET DEFINE OFF', 'WHENEVER SQLERROR EXIT SQL.SQLCODE', '']
    trg_install = [HEADER.format(title='Audit / tenant triggers install order'), 'SET DEFINE OFF',
                   'WHENEVER SQLERROR EXIT SQL.SQLCODE', '']
    for m in ORDER:
        out = [HEADER.format(title=f'Package {m.no:02d} - {m.en} | {m.ar} | {m.pkg}'),
               'SET DEFINE OFF', '']
        for t in m.tables:
            out.append(f'-- {"-" * 77}\n-- {t.name}: {t.ar} ({t.en})\n-- {"-" * 77}')
            out.append(table_ddl(t))
        out.append('-- ======================= Foreign keys =======================')
        for t, fk in fks_by_home[m.code]:
            out.append(fk_ddl(t, fk))
        out.append('\n-- ======================= Indexes =======================')
        for t in m.tables:
            out.extend(index_ddl(t))
        out.append('\n-- ======================= Comments (Data Dictionary) =======================')
        for t in m.tables:
            out.extend(comments_ddl(t))
            out.append('')
        write(f'db/ddl/{m.file_stem}.sql', '\n'.join(out) + '\n')
        install.append(f'PROMPT == {m.file_stem}: {m.en}')
        install.append(f'@@ddl/{m.file_stem}.sql')

        trg = [HEADER.format(title=f'Triggers - Package {m.no:02d} {m.en}'), 'SET DEFINE OFF', '']
        for t in m.tables:
            trg.append(trigger_ddl(t))
        write(f'db/triggers/{m.file_stem}_trg.sql', '\n'.join(trg))
        trg_install.append(f'@@triggers/{m.file_stem}_trg.sql')
    write('db/install_ddl.sql', '\n'.join(install) + '\n')
    write('db/install_triggers.sql', '\n'.join(trg_install) + '\n')

    # uninstall (reverse order)
    un = [HEADER.format(title='UNINSTALL - drops every NOONA table (DEV ONLY!)'), 'SET DEFINE OFF', '']
    for m in reversed(ORDER):
        for t in reversed(m.tables):
            un.append(f'DROP TABLE {t.name} CASCADE CONSTRAINTS PURGE;')
    write('db/admin/uninstall_tables_DEV_ONLY.sql', '\n'.join(un) + '\n')


# ---------------------------------------------------------------- ERD
def mm_type(c):
    return c.otype.split('(')[0].replace(' ', '_')


def key_marks(t, c):
    marks = []
    if c.name == 'ID':
        marks.append('PK')
    if any(fk['col'] == c.name for fk in t.fks):
        marks.append('FK')
    if any(c.name in u for u in t.uks if u != ('TENANT_ID', 'ID')) or any(c.name == u[-1] for u in t.nuks):
        marks.append('UK')
    return ','.join(marks)


def erd_entity(t, full=False):
    rows = []
    for c in t.cols:
        if c.name in ('ROW_VERSION', 'CREATED_BY', 'CREATED_AT', 'UPDATED_BY', 'UPDATED_AT'):
            continue
        mk = key_marks(t, c)
        if not full and not mk and c.name not in ('STATUS_CODE', 'NAME_AR', 'CODE', 'DOC_NO'):
            continue
        rows.append(f'    {mm_type(c)} {c.name}{(" " + mk) if mk else ""}')
    return f'  {t.name} {{\n' + '\n'.join(rows) + '\n  }'


def erd_rel(t, fk):
    p = TABLES[fk['ptab']]
    c = t.col(fk['col'])
    one_to_one = any(u == (fk['col'],) or u == ('TENANT_ID', fk['col']) for u in t.uks)
    left = '||' if not fk['nullable'] else '|o'
    right = 'o|' if one_to_one else 'o{'
    return f'  {p.name} {left}--{right} {t.name} : "{fk["col"]}"'


