# ---------------------------------------------------------------- Security (VPD, grants) & registry seed
def gen_security_and_seed():
    # VPD policies -------------------------------------------------------
    v = [HEADER.format(title='Row-Level Security (VPD) policies - tenant isolation for every tenant-owned table'),
         'SET DEFINE OFF', 'WHENEVER SQLERROR EXIT SQL.SQLCODE', '',
         '-- يشغل بعد 20_noona_vpd_pkg.sql. الجداول ذات النطاق T و C: عزل صارم على TENANT_ID.',
         '-- الجداول ذات النطاق TO: قراءة صفوف المنصة (TENANT_ID فارغ) + صفوف المؤسسة، والتعديل لصفوف المؤسسة فقط.',
         '-- الجداول ذات النطاق G (منصة) لا تخضع لـVPD ويتحكم بها عبر GRANTs والحزم.', '',
         'BEGIN']
    for t in sorted(TABLES.values(), key=lambda x: x.name):
        if t.scope in ('T', 'C'):
            v.append(f"  NOONA_VPD_PKG.add_tenant_policy('{t.name}');")
        elif t.scope == 'TO':
            v.append(f"  NOONA_VPD_PKG.add_shared_policy('{t.name}');")
    v += ['END;', '/']
    write('db/security/30_vpd_policies.sql', '\n'.join(v) + '\n')

    # Grants & synonyms ----------------------------------------------------
    g = [HEADER.format(title='Object grants for the APEX/ORDS parsing schema NOONA_APP (run as NOONA_OWNER)'),
         'SET DEFINE OFF', '',
         '-- الجداول Append-only (التدقيق والأحداث) تمنح SELECT فقط؛ الكتابة عبر حزم المالك (Definer Rights).']
    syn = [HEADER.format(title='Private synonyms in NOONA_APP (run as NOONA_APP)'), 'SET DEFINE OFF', '']
    # بيانات الاعتماد السرية لا تمنح للتطبيق إطلاقاً (التحقق والتخزين عبر حزم المالك فقط)
    secret = {'SEC_CREDENTIAL', 'SEC_MFA_FACTOR'}
    g.append('-- ' + ', '.join(sorted(secret)) + ': لا منح (بيانات اعتماد سرية؛ عبر NOONA_APEX_PKG و NOONA_SEC_ADMIN_PKG)')
    for t in sorted(TABLES.values(), key=lambda x: x.name):
        if t.name in secret:
            continue
        privs = 'SELECT' if t.append else 'SELECT, INSERT, UPDATE, DELETE'
        g.append(f'GRANT {privs} ON {t.name} TO NOONA_APP;')
        syn.append(f'CREATE OR REPLACE SYNONYM {t.name} FOR NOONA_OWNER.{t.name};')
    # NOONA_CTX_PKG و NOONA_CORE_PKG لا يمنحان للتطبيق (يمنع تجاوز VPD عبر وضع النظام)؛
    # يقرأ التطبيق السياق عبر SYS_CONTEXT('NOONA_CTX', ...)
    for pkg in ('NOONA_SECURITY_PKG', 'NOONA_REFERENCE_PKG', 'NOONA_AUDIT_PKG', 'NOONA_PLATFORM_PKG',
                'NOONA_ORG_PKG', 'NOONA_DELEGATION_PKG', 'NOONA_WORKFLOW_PKG', 'NOONA_APEX_PKG',
                'NOONA_PORTAL_PKG', 'NOONA_UI_PKG', 'NOONA_SEC_ADMIN_PKG', 'NOONA_BRAND_PKG', 'NOONA_REFDATA_PKG', 'NOONA_PLATFORM_ADMIN_PKG', 'NOONA_DMS_PKG', 'NOONA_PTY_PKG', 'NOONA_GL_PKG',
                'NOONA_CSH_PKG', 'NOONA_FIN_RPT_PKG', 'NOONA_INV_PKG', 'NOONA_PUR_PKG', 'NOONA_SAL_PKG', 'NOONA_POS_PKG', 'NOONA_MFG_PKG', 'NOONA_COR_PKG', 'NOONA_HR_PKG', 'NOONA_PAY_PKG', 'NOONA_FA_PKG', 'NOONA_RE_PKG', 'NOONA_HSP_PKG', 'NOONA_MNT_PKG', 'NOONA_RST_PKG', 'NOONA_HIS_PKG', 'NOONA_HIS_CARE_PKG', 'NOONA_HIS_CLAIM_PKG', 'NOONA_HIS_LINK_PKG', 'NOONA_HIS_CLIN_PKG', 'NOONA_HIS_NURSE_PKG', 'NOONA_BI_PKG', 'NOONA_PRJ_PKG', 'NOONA_LOC_PKG', 'NOONA_EINV_PKG'):
        g.append(f'GRANT EXECUTE ON {pkg} TO NOONA_APP;')
        syn.append(f'CREATE OR REPLACE SYNONYM {pkg} FOR NOONA_OWNER.{pkg};')
    # واجهات العرض المكتوبة يدوياً في db/plsql (قراءة فقط للتطبيق)
    for view in ('NOONA_V_MY_TASKS', 'NOONA_V_TASK_HISTORY', 'NOONA_V_MY_NOTIFICATIONS', 'NOONA_V_APPS', 'NOONA_V_TAX_REGISTER'):
        g.append(f'GRANT SELECT ON {view} TO NOONA_APP;')
        syn.append(f'CREATE OR REPLACE SYNONYM {view} FOR NOONA_OWNER.{view};')
    write('db/security/40_grants_noona_app.sql', '\n'.join(g) + '\n')
    write('db/security/41_synonyms_noona_app.sql', '\n'.join(syn) + '\n')

    # Registry seed --------------------------------------------------------
    sd = [HEADER.format(title='Registry seed: modules, entity type registry, atomic permission catalog'),
          'SET DEFINE OFF', 'WHENEVER SQLERROR EXIT SQL.SQLCODE', '']
    for m in sorted(MODULES, key=lambda x: x.no):
        core = 'Y' if m.code in ('REF', 'PLT', 'SEC', 'WF', 'DMS', 'COR', 'LOC') else 'N'
        sd.append(f"INSERT INTO PLT_MODULE (MODULE_CODE, PACKAGE_NO, PLSQL_PACKAGE, NAME_AR, NAME_EN, IS_CORE, SORT_ORDER) "
                  f"VALUES ('{m.code}', {m.no}, '{m.pkg}', '{q(m.ar)}', '{q(m.en)}', '{core}', {m.no});")
    sd.append('')
    perms = []
    for t in sorted(TABLES.values(), key=lambda x: x.name):
        if t.append:
            continue
        is_doc = bool(t.col('PUBLIC_ID') or t.col('DOC_NO'))
        sd.append(f"INSERT INTO REF_ENTITY_TYPE (ENTITY_TYPE_CODE, MODULE_CODE, TABLE_NAME, NAME_AR, NAME_EN, "
                  f"ALLOW_DMS_LINK, ALLOW_COR_LINK, HAS_COMPANY) VALUES ('{t.name}', '{t.module.code}', '{t.name}', "
                  f"'{q(t.ar)}', '{q(t.en)}', '{'Y' if is_doc else 'N'}', '{'Y' if is_doc else 'N'}', "
                  f"'{'Y' if t.scope == 'C' else 'N'}');")
        st = t.col('STATUS_CODE')
        if t.scope == 'G':
            actions = ['VIEW', 'CONFIGURE']
        else:
            actions = ['VIEW', 'CREATE', 'UPDATE', 'DELETE', 'EXPORT']
            if is_doc:
                actions.append('PRINT')
            if t.col('WF_INSTANCE_ID') or (st and st.check_in and ({'APPROVED', 'ACTIVE'} & set(st.check_in))):
                actions += ['SUBMIT', 'APPROVE', 'REJECT']
            if t.col('POSTED_AT'):
                actions += ['POST', 'REVERSE']
            if st and st.check_in and 'CANCELLED' in st.check_in:
                actions.append('CANCEL')
        for a in actions:
            risk = 'HIGH' if a in ('APPROVE', 'POST', 'REVERSE', 'CONFIGURE', 'DELETE', 'EXPORT') else 'NORMAL'
            perms.append((f'{t.name}.{a}', t.module.code, t.name, a, risk, t.ar))
    sd.append('')
    for code, mod, res, act, risk, ar in perms:
        sd.append(f"INSERT INTO SEC_PERMISSION (PERMISSION_CODE, MODULE_CODE, RESOURCE_CODE, ACTION_CODE, RISK_LEVEL, "
                  f"REQUIRES_MFA, NAME_AR, NAME_EN) VALUES ('{code}', '{mod}', '{res}', '{act}', '{risk}', "
                  f"'{'Y' if risk == 'HIGH' and act in ('POST', 'REVERSE', 'CONFIGURE') else 'N'}', "
                  f"'{q(ar)} - {act}', '{res} {act}');")
    sd += ['', 'COMMIT;']
    write('db/seed/01_registry_seed.sql', '\n'.join(sd) + '\n')
    return len(perms)


