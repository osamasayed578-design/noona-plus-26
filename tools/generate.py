def md_escape(s):
    return (s or '').replace('|', '\\|').replace('\n', ' ')


def col_keys(t, c):
    k = []
    if c.name == 'ID':
        k.append('PK')
    for fk in t.fks:
        if fk['col'] == c.name:
            k.append(f'FK→{fk["ptab"]}')
    for i, u in enumerate(t.uks, 1):
        if c.name in u and u != ('TENANT_ID', 'ID'):
            k.append(f'UK{i}')
    for i, u in enumerate(t.nuks, 1):
        if c.name == u[-1]:
            k.append(f'NUK{i}')
    return ' '.join(k)


def accepted(c):
    if c.check_in:
        return ', '.join(c.check_in)
    if c.ltype == 'YN':
        return 'Y, N'
    if c.ltype == 'JSON':
        return 'JSON صالح'
    return ''


