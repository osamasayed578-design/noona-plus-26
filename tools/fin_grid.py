"""شبكة إدخال السطور (رأس وتفاصيل) المشتركة في تطبيق المالية: القيود (مدين/دائن) والسندات (مبلغ).
الحاوية: <div id="nnJe" data-kind="JE|CV" data-item="P21_LINES" data-readonly="Y|N">
البيانات: <script type="application/json"> بالمعرفات nnJeLines (السطور) و nnJeAccts (الحسابات) و nnJeCcs (مراكز التكلفة).
قبل الإرسال تكتب السطور JSON في العنصر المخفي: قيد {a,d,c,cc,t} وسند {a,m,cc,t}.
"""


def grid_region(lines_sql, accounts_sql, readonly_sql, kind, item):
    """كود PL/SQL للمنطقة الديناميكية: السطور من العنصر المخفي إن وجد (بعد خطأ تحقق) وإلا من القاعدة."""
    return [
        'declare',
        f'    l_ro varchar2(1) := {readonly_sql};',
        'begin',
        f"    return '<script type=\"application/json\" id=\"nnJeLines\">' || replace(nvl(:{item}, {lines_sql}), '</', '<\\/') || '</script>'",
        "        || case when l_ro = 'N' then '<script type=\"application/json\" id=\"nnJeAccts\">'",
        f"                || replace({accounts_sql}, '</', '<\\/') || '</script>' end",
        "        || '<script type=\"application/json\" id=\"nnJeCcs\">' || replace(noona_gl_pkg.cost_centers_json, '</', '<\\/') || '</script>'",
        f"        || '<div id=\"nnJe\" class=\"nn-je\" data-kind=\"{kind}\" data-item=\"{item}\" data-readonly=\"' || l_ro || '\"></div>';",
        'end;']


