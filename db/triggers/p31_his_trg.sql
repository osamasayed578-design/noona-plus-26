CREATE OR REPLACE TRIGGER HIS_DEPARTMENT_BIU
BEFORE INSERT OR UPDATE ON HIS_DEPARTMENT
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    IF :NEW.TENANT_ID IS NULL THEN
      :NEW.TENANT_ID := NOONA_CTX_PKG.TENANT_ID;
    END IF;
    :NEW.CREATED_BY  := COALESCE(:NEW.CREATED_BY, NOONA_CTX_PKG.CURRENT_USER_NAME);
    :NEW.CREATED_AT  := SYSTIMESTAMP;
    :NEW.ROW_VERSION := 1;
  ELSE
    IF NOT ((:NEW.TENANT_ID = :OLD.TENANT_ID) OR (:NEW.TENANT_ID IS NULL AND :OLD.TENANT_ID IS NULL)) THEN
      RAISE_APPLICATION_ERROR(-20001, 'NOONA-SEC-001: TENANT_ID is immutable');
    END IF;
    :NEW.CREATED_BY  := :OLD.CREATED_BY;
    :NEW.CREATED_AT  := :OLD.CREATED_AT;
    :NEW.ROW_VERSION := NVL(:OLD.ROW_VERSION, 0) + 1;
    :NEW.UPDATED_BY  := NOONA_CTX_PKG.CURRENT_USER_NAME;
    :NEW.UPDATED_AT  := SYSTIMESTAMP;
  END IF;
END;
