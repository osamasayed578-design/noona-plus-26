    NULL; -- حذف مسموح فقط عبر إجراء الإتلاف المعتمد
  ELSE
    RAISE_APPLICATION_ERROR(-20002, 'NOONA-AUD-001: DEP_SCHEMA_MIGRATION is append-only');
  END IF;
END;
