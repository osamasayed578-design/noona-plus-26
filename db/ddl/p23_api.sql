  CONSTRAINT API_INTEGRATION_AUTH_METHOD_CK CHECK (AUTH_METHOD IN ('API_KEY', 'OAUTH2', 'MTLS', 'BASIC', 'JWT', 'HMAC', 'CERTIFICATE')),
  CONSTRAINT API_INTEGRATION_HANDLES_PII_CK CHECK (HANDLES_PII IN ('Y', 'N')),
