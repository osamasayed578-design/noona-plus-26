  CONSTRAINT API_INTEGRATION_UK1 UNIQUE (TENANT_ID, CODE),
  CONSTRAINT API_INTEGRATION_INTEGRATION_TYPE_CK CHECK (INTEGRATION_TYPE IN ('PAYMENT_GATEWAY', 'BANK', 'EMAIL', 'SMS', 'WHATSAPP', 'PUSH', 'E_INVOICE', 'E_SIGNATURE', 'GOVERNMENT', 'PARTNER', 'AI', 'OCR', 'STORAGE', 'IDENTITY', 'OTHER')),
