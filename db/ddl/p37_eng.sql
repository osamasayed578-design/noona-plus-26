-- -----------------------------------------------------------------------------
-- ENG_PORTAL_LINK: روابط بوابة العملاء (Customer Portal Links)
-- -----------------------------------------------------------------------------
CREATE TABLE ENG_PORTAL_LINK (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  COMPANY_ID                       NUMBER(19) NOT NULL,
  CUSTOMER_ACCOUNT_ID              NUMBER(19) NOT NULL,
  TOKEN_HASH                       VARCHAR2(64 CHAR) NOT NULL,
  TOKEN_ENC                        VARCHAR2(500 CHAR),
  TOKEN_HINT                       VARCHAR2(20 CHAR),
  EXPIRES_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  LAST_ACCESS_AT                   TIMESTAMP(6) WITH LOCAL TIME ZONE,
  ACCESS_COUNT                     NUMBER(10) DEFAULT ON NULL 0 NOT NULL,
  PHONE                            VARCHAR2(30 CHAR),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'ACTIVE' NOT NULL,
  NOTES                            VARCHAR2(4000 CHAR),
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT ENG_PORTAL_LINK_PK PRIMARY KEY (ID),
  CONSTRAINT ENG_PORTAL_LINK_UK1 UNIQUE (TOKEN_HASH),
  CONSTRAINT ENG_PORTAL_LINK_STATUS_CODE_CK CHECK (STATUS_CODE IN ('ACTIVE', 'REVOKED'))
);

-- -----------------------------------------------------------------------------
-- ENG_WA_SETTING: إعدادات واتساب (WhatsApp Settings)
-- -----------------------------------------------------------------------------
CREATE TABLE ENG_WA_SETTING (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  COMPANY_ID                       NUMBER(19) NOT NULL,
  PROVIDER                         VARCHAR2(30 CHAR) DEFAULT ON NULL 'LINK' NOT NULL,
  PHONE_NUMBER_ID                  VARCHAR2(50 CHAR),
  BUSINESS_ACCOUNT_ID              VARCHAR2(50 CHAR),
  API_VERSION                      VARCHAR2(10 CHAR) DEFAULT ON NULL 'v21.0' NOT NULL,
  TOKEN_ENC                        VARCHAR2(2000 CHAR),
  DEFAULT_CC                       VARCHAR2(5 CHAR) DEFAULT ON NULL '966' NOT NULL,
  SENDER_PHONE                     VARCHAR2(30 CHAR),
  IS_ENABLED                       CHAR(1 CHAR) DEFAULT ON NULL 'Y' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT ENG_WA_SETTING_PK PRIMARY KEY (ID),
  CONSTRAINT ENG_WA_SETTING_UK1 UNIQUE (TENANT_ID, COMPANY_ID),
  CONSTRAINT ENG_WA_SETTING_PROVIDER_CK CHECK (PROVIDER IN ('LINK', 'CLOUD_API')),
  CONSTRAINT ENG_WA_SETTING_IS_ENABLED_CK CHECK (IS_ENABLED IN ('Y', 'N'))
