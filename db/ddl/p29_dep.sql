-- -----------------------------------------------------------------------------
-- DEP_RELEASE: الإصدارات (Releases)
-- -----------------------------------------------------------------------------
CREATE TABLE DEP_RELEASE (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  VERSION_LABEL                    VARCHAR2(30 CHAR) NOT NULL,
  RELEASE_TYPE                     VARCHAR2(30 CHAR) NOT NULL,
  CHANNEL                          VARCHAR2(30 CHAR) DEFAULT ON NULL 'INTERNAL' NOT NULL,
  RELEASE_NOTES                    CLOB,
  PACKAGE_SIGNATURE                VARCHAR2(4000 CHAR),
  RELEASED_AT                      TIMESTAMP(6) WITH LOCAL TIME ZONE,
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'PLANNED' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT DEP_RELEASE_PK PRIMARY KEY (ID),
  CONSTRAINT DEP_RELEASE_UK1 UNIQUE (VERSION_LABEL),
  CONSTRAINT DEP_RELEASE_RELEASE_TYPE_CK CHECK (RELEASE_TYPE IN ('MAJOR', 'MINOR', 'PATCH', 'HOTFIX')),
  CONSTRAINT DEP_RELEASE_CHANNEL_CK CHECK (CHANNEL IN ('INTERNAL', 'PILOT', 'EARLY_ACCESS', 'GENERAL_AVAILABILITY', 'ON_PREMISES_PACKAGE', 'LTS')),
  CONSTRAINT DEP_RELEASE_STATUS_CODE_CK CHECK (STATUS_CODE IN ('PLANNED', 'BUILT', 'TESTED', 'APPROVED', 'ROLLING_OUT', 'RELEASED', 'ROLLED_BACK', 'RETIRED'))
);

-- -----------------------------------------------------------------------------
-- DEP_COMPONENT_VERSION: إصدارات المكونات (Release Component Versions)
-- -----------------------------------------------------------------------------
CREATE TABLE DEP_COMPONENT_VERSION (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  RELEASE_ID                       NUMBER(19) NOT NULL,
  COMPONENT_CODE                   VARCHAR2(30 CHAR) NOT NULL,
  COMPONENT_VERSION                VARCHAR2(50 CHAR) NOT NULL,
  MIN_COMPATIBLE                   VARCHAR2(50 CHAR),
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT DEP_COMPONENT_VERSION_PK PRIMARY KEY (ID),
  CONSTRAINT DEP_COMPONENT_VERSION_UK1 UNIQUE (RELEASE_ID, COMPONENT_CODE),
  CONSTRAINT DEP_COMPONENT_VERSION_COMPONENT_CODE_CK CHECK (COMPONENT_CODE IN ('DB_SCHEMA', 'PLSQL', 'APEX_APP', 'ORDS', 'API', 'COUNTRY_PACK', 'AI_RAG', 'DOC_STORAGE'))
);

-- -----------------------------------------------------------------------------
-- DEP_SCHEMA_MIGRATION: سجل ترحيلات المخطط (Schema Migrations)
-- -----------------------------------------------------------------------------
CREATE TABLE DEP_SCHEMA_MIGRATION (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  SCRIPT_NAME                      VARCHAR2(200 CHAR) NOT NULL,
  SCRIPT_VERSION                   VARCHAR2(30 CHAR) NOT NULL,
  CHECKSUM                         VARCHAR2(128 CHAR) NOT NULL,
  RELEASE_ID                       NUMBER(19),
  EXECUTION_MS                     NUMBER(10),
  RESULT_CODE                      VARCHAR2(30 CHAR) NOT NULL,
  ERROR_MESSAGE                    VARCHAR2(4000 CHAR),
  ROLLBACK_SCRIPT                  VARCHAR2(200 CHAR),
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  CONSTRAINT DEP_SCHEMA_MIGRATION_PK PRIMARY KEY (ID),
  CONSTRAINT DEP_SCHEMA_MIGRATION_UK1 UNIQUE (SCRIPT_NAME),
  CONSTRAINT DEP_SCHEMA_MIGRATION_RESULT_CODE_CK CHECK (RESULT_CODE IN ('SUCCESS', 'FAILED', 'ROLLED_BACK', 'FORWARD_FIXED'))
);

-- -----------------------------------------------------------------------------
-- DEP_DEPLOYMENT: عمليات النشر (Deployments)
-- -----------------------------------------------------------------------------
CREATE TABLE DEP_DEPLOYMENT (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  RELEASE_ID                       NUMBER(19) NOT NULL,
  CELL_ID                          NUMBER(19),
  ENVIRONMENT_CODE                 VARCHAR2(30 CHAR) NOT NULL,
  ROLLOUT_WAVE                     VARCHAR2(30 CHAR),
  WINDOW_START                     TIMESTAMP(6) WITH LOCAL TIME ZONE,
  WINDOW_END                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  OWNER_NAME                       VARCHAR2(200 CHAR),
  ROLLBACK_PLAN                    VARCHAR2(4000 CHAR),
  STARTED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  FINISHED_AT                      TIMESTAMP(6) WITH LOCAL TIME ZONE,
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'SCHEDULED' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT DEP_DEPLOYMENT_PK PRIMARY KEY (ID),
  CONSTRAINT DEP_DEPLOYMENT_ENVIRONMENT_CODE_CK CHECK (ENVIRONMENT_CODE IN ('DEV', 'TEST', 'UAT', 'PREPROD', 'PROD', 'DR')),
  CONSTRAINT DEP_DEPLOYMENT_ROLLOUT_WAVE_CK CHECK (ROLLOUT_WAVE IN ('INTERNAL', 'PILOT', 'LIMITED', 'GENERAL')),
  CONSTRAINT DEP_DEPLOYMENT_STATUS_CODE_CK CHECK (STATUS_CODE IN ('SCHEDULED', 'IN_PROGRESS', 'HEALTH_CHECK', 'SUCCEEDED', 'FAILED', 'ROLLED_BACK'))
);

-- -----------------------------------------------------------------------------
-- DEP_HEALTH_CHECK: فحوص الصحة (Health Checks)
-- -----------------------------------------------------------------------------
CREATE TABLE DEP_HEALTH_CHECK (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  DEPLOYMENT_ID                    NUMBER(19) NOT NULL,
  CHECK_CODE                       VARCHAR2(50 CHAR) NOT NULL,
  RESULT_CODE                      VARCHAR2(30 CHAR) NOT NULL,
  DETAILS                          VARCHAR2(4000 CHAR),
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  CONSTRAINT DEP_HEALTH_CHECK_PK PRIMARY KEY (ID),
  CONSTRAINT DEP_HEALTH_CHECK_RESULT_CODE_CK CHECK (RESULT_CODE IN ('PASS', 'FAIL', 'WARN'))
);

-- -----------------------------------------------------------------------------
-- DEP_TENANT_VERSION: إصدارات مكونات المؤسسة (Tenant Component Versions)
-- -----------------------------------------------------------------------------
CREATE TABLE DEP_TENANT_VERSION (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  COMPONENT_CODE                   VARCHAR2(30 CHAR) NOT NULL,
  COMPONENT_VERSION                VARCHAR2(50 CHAR) NOT NULL,
  RELEASE_ID                       NUMBER(19),
  UPGRADED_AT                      TIMESTAMP(6) WITH LOCAL TIME ZONE,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT DEP_TENANT_VERSION_PK PRIMARY KEY (ID),
  CONSTRAINT DEP_TENANT_VERSION_UK1 UNIQUE (TENANT_ID, COMPONENT_CODE),
  CONSTRAINT DEP_TENANT_VERSION_COMPONENT_CODE_CK CHECK (COMPONENT_CODE IN ('DB_SCHEMA', 'PLSQL', 'APEX_APP', 'ORDS', 'API', 'COUNTRY_PACK', 'AI_RAG', 'DOC_STORAGE'))
);

