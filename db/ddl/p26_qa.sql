SET DEFINE OFF

-- -----------------------------------------------------------------------------
-- QA_REQUIREMENT: سجل المتطلبات (Requirements Register)
-- -----------------------------------------------------------------------------
CREATE TABLE QA_REQUIREMENT (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  REQ_TYPE                         VARCHAR2(30 CHAR) NOT NULL,
  TITLE_AR                         VARCHAR2(1000 CHAR) NOT NULL,
  DESCRIPTION                      VARCHAR2(4000 CHAR),
  PRIORITY_CODE                    VARCHAR2(30 CHAR),
  MODULE_CODE                      VARCHAR2(30 CHAR),
  SOURCE_REF                       VARCHAR2(200 CHAR),
  OWNER_NAME                       VARCHAR2(200 CHAR),
  ACCEPTANCE_CRITERIA              VARCHAR2(4000 CHAR),
  RELEASE_TARGET                   VARCHAR2(20 CHAR),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'PROPOSED' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT QA_REQUIREMENT_PK PRIMARY KEY (ID),
  CONSTRAINT QA_REQUIREMENT_UK1 UNIQUE (CODE),
  CONSTRAINT QA_REQUIREMENT_REQ_TYPE_CK CHECK (REQ_TYPE IN ('FUNCTIONAL', 'NON_FUNCTIONAL', 'BUSINESS_RULE', 'DECISION', 'RISK')),
  CONSTRAINT QA_REQUIREMENT_PRIORITY_CODE_CK CHECK (PRIORITY_CODE IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
  CONSTRAINT QA_REQUIREMENT_STATUS_CODE_CK CHECK (STATUS_CODE IN ('PROPOSED', 'APPROVED', 'IMPLEMENTED', 'VERIFIED', 'DEFERRED', 'REJECTED'))
);

-- -----------------------------------------------------------------------------
-- QA_TEST_SUITE: مجموعات الاختبار (Test Suites)
-- -----------------------------------------------------------------------------
CREATE TABLE QA_TEST_SUITE (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  NAME_AR                          VARCHAR2(200 CHAR) NOT NULL,
  NAME_EN                          VARCHAR2(200 CHAR),
  MODULE_CODE                      VARCHAR2(30 CHAR),
  TEST_LEVEL                       VARCHAR2(30 CHAR) NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT QA_TEST_SUITE_PK PRIMARY KEY (ID),
  CONSTRAINT QA_TEST_SUITE_UK1 UNIQUE (CODE),
  CONSTRAINT QA_TEST_SUITE_TEST_LEVEL_CK CHECK (TEST_LEVEL IN ('UNIT', 'MODULE', 'INTEGRATION', 'ACCOUNTING', 'WORKFLOW', 'SECURITY', 'PERFORMANCE', 'UAT', 'REGRESSION'))
);

-- -----------------------------------------------------------------------------
-- QA_TEST_CASE: حالات الاختبار (Test Cases)
-- -----------------------------------------------------------------------------
CREATE TABLE QA_TEST_CASE (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  SUITE_ID                         NUMBER(19) NOT NULL,
  TITLE_AR                         VARCHAR2(1000 CHAR) NOT NULL,
  PRECONDITIONS                    VARCHAR2(4000 CHAR),
  STEPS                            CLOB,
  EXPECTED_RESULT                  VARCHAR2(4000 CHAR) NOT NULL,
  TEST_DATA_REF                    VARCHAR2(500 CHAR),
  IS_AUTOMATED                     CHAR(1 CHAR) DEFAULT ON NULL 'N' NOT NULL,
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'DRAFT' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT QA_TEST_CASE_PK PRIMARY KEY (ID),
  CONSTRAINT QA_TEST_CASE_UK1 UNIQUE (CODE),
  CONSTRAINT QA_TEST_CASE_IS_AUTOMATED_CK CHECK (IS_AUTOMATED IN ('Y', 'N')),
  CONSTRAINT QA_TEST_CASE_STATUS_CODE_CK CHECK (STATUS_CODE IN ('DRAFT', 'READY', 'OBSOLETE'))
);

-- -----------------------------------------------------------------------------
-- QA_TRACE_LINK: روابط التتبع (Traceability Links)
-- -----------------------------------------------------------------------------
CREATE TABLE QA_TRACE_LINK (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  REQUIREMENT_ID                   NUMBER(19) NOT NULL,
  TEST_CASE_ID                     NUMBER(19) NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT QA_TRACE_LINK_PK PRIMARY KEY (ID),
  CONSTRAINT QA_TRACE_LINK_UK1 UNIQUE (REQUIREMENT_ID, TEST_CASE_ID)
);

-- -----------------------------------------------------------------------------
-- QA_TEST_RUN: تشغيلات الاختبار (Test Runs)
-- -----------------------------------------------------------------------------
CREATE TABLE QA_TEST_RUN (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  RUN_NAME                         VARCHAR2(200 CHAR) NOT NULL,
  ENVIRONMENT_CODE                 VARCHAR2(30 CHAR) NOT NULL,
  RELEASE_VERSION                  VARCHAR2(30 CHAR),
  STARTED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  FINISHED_AT                      TIMESTAMP(6) WITH LOCAL TIME ZONE,
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'PLANNED' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT QA_TEST_RUN_PK PRIMARY KEY (ID),
  CONSTRAINT QA_TEST_RUN_ENVIRONMENT_CODE_CK CHECK (ENVIRONMENT_CODE IN ('DEV', 'TEST', 'UAT', 'PREPROD')),
  CONSTRAINT QA_TEST_RUN_STATUS_CODE_CK CHECK (STATUS_CODE IN ('PLANNED', 'RUNNING', 'COMPLETED', 'ABORTED'))
);

-- -----------------------------------------------------------------------------
-- QA_TEST_RESULT: نتائج الاختبار (Test Results)
-- -----------------------------------------------------------------------------
CREATE TABLE QA_TEST_RESULT (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  RUN_ID                           NUMBER(19) NOT NULL,
  TEST_CASE_ID                     NUMBER(19) NOT NULL,
  RESULT_CODE                      VARCHAR2(30 CHAR) NOT NULL,
  ACTUAL_RESULT                    VARCHAR2(4000 CHAR),
  EVIDENCE_REF                     VARCHAR2(500 CHAR),
  EXECUTED_BY                      VARCHAR2(128 CHAR),
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  CONSTRAINT QA_TEST_RESULT_PK PRIMARY KEY (ID),
  CONSTRAINT QA_TEST_RESULT_RESULT_CODE_CK CHECK (RESULT_CODE IN ('PASS', 'FAIL', 'BLOCKED', 'SKIPPED'))
);

-- -----------------------------------------------------------------------------
-- QA_DEFECT: العيوب (Defects)
-- -----------------------------------------------------------------------------
CREATE TABLE QA_DEFECT (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  TITLE                            VARCHAR2(1000 CHAR) NOT NULL,
  SEVERITY                         VARCHAR2(30 CHAR) NOT NULL,
  TEST_RESULT_ID                   NUMBER(19),
  REQUIREMENT_ID                   NUMBER(19),
  MODULE_CODE                      VARCHAR2(30 CHAR),
  FIX_VERSION                      VARCHAR2(30 CHAR),
  ACCEPTED_BY                      VARCHAR2(128 CHAR),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'NEW' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT QA_DEFECT_PK PRIMARY KEY (ID),
  CONSTRAINT QA_DEFECT_UK1 UNIQUE (CODE),
  CONSTRAINT QA_DEFECT_SEVERITY_CK CHECK (SEVERITY IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
  CONSTRAINT QA_DEFECT_STATUS_CODE_CK CHECK (STATUS_CODE IN ('NEW', 'TRIAGED', 'IN_PROGRESS', 'FIXED', 'RETEST', 'VERIFIED', 'CLOSED', 'REJECTED'))
);

