SET DEFINE OFF

-- -----------------------------------------------------------------------------
-- PIL_PILOT: المشروعات التجريبية (Pilots)
-- -----------------------------------------------------------------------------
CREATE TABLE PIL_PILOT (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  NAME_AR                          VARCHAR2(200 CHAR) NOT NULL,
  NAME_EN                          VARCHAR2(200 CHAR),
  TRIAL_ID                         NUMBER(19),
  SCOPE_MODULES                    VARCHAR2(1000 CHAR),
  USER_LIMIT                       NUMBER(10),
  START_DATE                       DATE NOT NULL,
  END_DATE                         DATE NOT NULL,
  SPONSOR_NAME                     VARCHAR2(200 CHAR),
  DATA_FATE                        VARCHAR2(30 CHAR),
  GO_LIVE_DECISION                 VARCHAR2(30 CHAR),
  DECISION_DATE                    DATE,
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'PLANNED' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT PIL_PILOT_PK PRIMARY KEY (ID),
  CONSTRAINT PIL_PILOT_UK1 UNIQUE (TENANT_ID, ID),
  CONSTRAINT PIL_PILOT_UK2 UNIQUE (TENANT_ID, CODE),
  CONSTRAINT PIL_PILOT_DATA_FATE_CK CHECK (DATA_FATE IN ('KEEP', 'EXPORT_AND_ARCHIVE', 'PURGE_AFTER_RETENTION')),
  CONSTRAINT PIL_PILOT_GO_LIVE_DECISION_CK CHECK (GO_LIVE_DECISION IN ('GO', 'NO_GO', 'EXTEND')),
  CONSTRAINT PIL_PILOT_STATUS_CODE_CK CHECK (STATUS_CODE IN ('PLANNED', 'ACTIVE', 'EXTENDED', 'SUCCEEDED', 'FAILED', 'CONVERTED', 'CLOSED'))
);

-- -----------------------------------------------------------------------------
-- PIL_SUCCESS_CRITERION: معايير النجاح (Success Criteria)
-- -----------------------------------------------------------------------------
CREATE TABLE PIL_SUCCESS_CRITERION (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  PILOT_ID                         NUMBER(19) NOT NULL,
  CRITERION_TEXT                   VARCHAR2(1000 CHAR) NOT NULL,
  TARGET_VALUE                     VARCHAR2(200 CHAR),
  ACTUAL_VALUE                     VARCHAR2(200 CHAR),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'PENDING' NOT NULL,
  SORT_ORDER                       NUMBER(10),
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT PIL_SUCCESS_CRITERION_PK PRIMARY KEY (ID),
  CONSTRAINT PIL_SUCCESS_CRITERION_STATUS_CODE_CK CHECK (STATUS_CODE IN ('PENDING', 'MET', 'NOT_MET', 'WAIVED'))
);

-- -----------------------------------------------------------------------------
-- PIL_FEEDBACK: ملاحظات المستخدمين (Pilot Feedback)
-- -----------------------------------------------------------------------------
CREATE TABLE PIL_FEEDBACK (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  PILOT_ID                         NUMBER(19) NOT NULL,
  MEMBERSHIP_ID                    NUMBER(19),
  MODULE_CODE                      VARCHAR2(30 CHAR),
  FEEDBACK_TYPE                    VARCHAR2(30 CHAR) NOT NULL,
  DESCRIPTION                      VARCHAR2(4000 CHAR) NOT NULL,
  DEFECT_ID                        NUMBER(19),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'NEW' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT PIL_FEEDBACK_PK PRIMARY KEY (ID),
  CONSTRAINT PIL_FEEDBACK_FEEDBACK_TYPE_CK CHECK (FEEDBACK_TYPE IN ('BUG', 'USABILITY', 'FEATURE_REQUEST', 'PERFORMANCE', 'PRAISE')),
  CONSTRAINT PIL_FEEDBACK_STATUS_CODE_CK CHECK (STATUS_CODE IN ('NEW', 'ACCEPTED', 'PLANNED', 'DONE', 'REJECTED'))
);

-- -----------------------------------------------------------------------------
-- PIL_USAGE_METRIC: مقاييس الاستخدام التجريبي (Pilot Usage Metrics)
-- -----------------------------------------------------------------------------
CREATE TABLE PIL_USAGE_METRIC (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  PILOT_ID                         NUMBER(19) NOT NULL,
  METRIC_DATE                      DATE NOT NULL,
  METRIC_CODE                      VARCHAR2(50 CHAR) NOT NULL,
  METRIC_VALUE                     NUMBER NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  CONSTRAINT PIL_USAGE_METRIC_PK PRIMARY KEY (ID)
);

