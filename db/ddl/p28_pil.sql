ALTER TABLE PIL_SUCCESS_CRITERION ADD CONSTRAINT PIL_SUCCESS_CRITERION_PILOT_ID_FK FOREIGN KEY (TENANT_ID, PILOT_ID) REFERENCES PIL_PILOT (TENANT_ID, ID);
ALTER TABLE PIL_FEEDBACK ADD CONSTRAINT PIL_FEEDBACK_TENANT_ID_FK FOREIGN KEY (TENANT_ID) REFERENCES PLT_TENANT (ID);
ALTER TABLE PIL_FEEDBACK ADD CONSTRAINT PIL_FEEDBACK_PILOT_ID_FK FOREIGN KEY (TENANT_ID, PILOT_ID) REFERENCES PIL_PILOT (TENANT_ID, ID);
