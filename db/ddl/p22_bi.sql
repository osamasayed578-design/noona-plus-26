-- -----------------------------------------------------------------------------
-- BI_REPORT_SCHEDULE: جدولة التقارير (Report Schedules)
-- -----------------------------------------------------------------------------
CREATE TABLE BI_REPORT_SCHEDULE (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  REPORT_ID                        NUMBER(19) NOT NULL,
  OWNER_MEMBER_ID                  NUMBER(19) NOT NULL,
