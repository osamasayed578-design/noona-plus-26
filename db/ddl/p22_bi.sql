-- -----------------------------------------------------------------------------
-- BI_KPI: تعريفات المؤشرات (KPI Definitions)
-- -----------------------------------------------------------------------------
CREATE TABLE BI_KPI (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19),
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  NAME_AR                          VARCHAR2(200 CHAR) NOT NULL,
  NAME_EN                          VARCHAR2(200 CHAR),
  DESCRIPTION                      VARCHAR2(4000 CHAR),
  MODULE_CODE                      VARCHAR2(30 CHAR) NOT NULL,
  VERSION_NO                       NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  OWNER_ROLE_ID                    NUMBER(19),
  FORMULA_TEXT                     VARCHAR2(4000 CHAR) NOT NULL,
  SOURCE_OBJECT                    VARCHAR2(128 CHAR),
  UNIT_CODE                        VARCHAR2(30 CHAR),
  PERIOD_SEMANTICS                 VARCHAR2(200 CHAR),
  CURRENCY_RULE                    VARCHAR2(200 CHAR),
  REFRESH_FREQUENCY                VARCHAR2(30 CHAR),
  DRILL_TARGET                     VARCHAR2(200 CHAR),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'DRAFT' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT BI_KPI_PK PRIMARY KEY (ID),
  CONSTRAINT BI_KPI_UK1 UNIQUE (TENANT_ID, CODE, VERSION_NO),
  CONSTRAINT BI_KPI_REFRESH_FREQUENCY_CK CHECK (REFRESH_FREQUENCY IN ('REALTIME', 'HOURLY', 'DAILY', 'WEEKLY', 'MONTHLY')),
  CONSTRAINT BI_KPI_STATUS_CODE_CK CHECK (STATUS_CODE IN ('DRAFT', 'PUBLISHED', 'RETIRED'))
);

-- -----------------------------------------------------------------------------
-- BI_KPI_VALUE: قيم المؤشرات (KPI Snapshots)
-- -----------------------------------------------------------------------------
CREATE TABLE BI_KPI_VALUE (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  KPI_ID                           NUMBER(19) NOT NULL,
  COMPANY_ID                       NUMBER(19),
  BRANCH_ID                        NUMBER(19),
  PERIOD_CODE                      VARCHAR2(20 CHAR) NOT NULL,
  AS_OF_TS                         TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
  VALUE_NUMBER                     NUMBER,
  TARGET_NUMBER                    NUMBER,
  CURRENCY_CODE                    VARCHAR2(3 CHAR),
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  CONSTRAINT BI_KPI_VALUE_PK PRIMARY KEY (ID)
);

-- -----------------------------------------------------------------------------
-- BI_REPORT: كتالوج التقارير (Report Catalog)
-- -----------------------------------------------------------------------------
CREATE TABLE BI_REPORT (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19),
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  NAME_AR                          VARCHAR2(200 CHAR) NOT NULL,
  NAME_EN                          VARCHAR2(200 CHAR),
  DESCRIPTION                      VARCHAR2(4000 CHAR),
  MODULE_CODE                      VARCHAR2(30 CHAR) NOT NULL,
  REPORT_TYPE                      VARCHAR2(30 CHAR) NOT NULL,
  VERSION_NO                       NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  PERMISSION_ID                    NUMBER(19),
  APEX_PAGE_ID                     NUMBER(10),
  OUTPUT_FORMATS                   VARCHAR2(100 CHAR),
  MANDATORY_FILTERS                VARCHAR2(1000 CHAR),
  IS_AS_OF_CAPABLE                 CHAR(1 CHAR) DEFAULT ON NULL 'N' NOT NULL,
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'DRAFT' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT BI_REPORT_PK PRIMARY KEY (ID),
  CONSTRAINT BI_REPORT_UK1 UNIQUE (TENANT_ID, CODE, VERSION_NO),
  CONSTRAINT BI_REPORT_REPORT_TYPE_CK CHECK (REPORT_TYPE IN ('OPERATIONAL', 'FINANCIAL', 'MANAGEMENT', 'REGULATORY', 'ANALYTICAL')),
  CONSTRAINT BI_REPORT_IS_AS_OF_CAPABLE_CK CHECK (IS_AS_OF_CAPABLE IN ('Y', 'N')),
  CONSTRAINT BI_REPORT_STATUS_CODE_CK CHECK (STATUS_CODE IN ('DRAFT', 'PUBLISHED', 'RETIRED'))
);

-- -----------------------------------------------------------------------------
-- BI_DASHBOARD: لوحات المعلومات (Dashboards)
-- -----------------------------------------------------------------------------
CREATE TABLE BI_DASHBOARD (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19),
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  NAME_AR                          VARCHAR2(200 CHAR) NOT NULL,
  NAME_EN                          VARCHAR2(200 CHAR),
  AUDIENCE                         VARCHAR2(30 CHAR) NOT NULL,
  APEX_PAGE_ID                     NUMBER(10),
  LAYOUT                           CLOB,
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'DRAFT' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT BI_DASHBOARD_PK PRIMARY KEY (ID),
  CONSTRAINT BI_DASHBOARD_UK1 UNIQUE (TENANT_ID, CODE),
  CONSTRAINT BI_DASHBOARD_AUDIENCE_CK CHECK (AUDIENCE IN ('PLATFORM', 'TENANT_ADMIN', 'EXECUTIVE', 'FINANCE', 'OPERATIONS', 'HR', 'PROJECTS', 'PROPERTY', 'PERSONAL')),
  CONSTRAINT BI_DASHBOARD_LAYOUT_JS CHECK (LAYOUT IS JSON),
  CONSTRAINT BI_DASHBOARD_STATUS_CODE_CK CHECK (STATUS_CODE IN ('DRAFT', 'PUBLISHED', 'RETIRED'))
