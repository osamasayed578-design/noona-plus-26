  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'ACTIVE' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT BI_REPORT_SCHEDULE_PK PRIMARY KEY (ID),
  CONSTRAINT BI_REPORT_SCHEDULE_PARAMETERS_JS CHECK (PARAMETERS IS JSON),
  CONSTRAINT BI_REPORT_SCHEDULE_OUTPUT_FORMAT_CK CHECK (OUTPUT_FORMAT IN ('PDF', 'XLSX', 'CSV', 'HTML')),
  CONSTRAINT BI_REPORT_SCHEDULE_RECIPIENTS_JS CHECK (RECIPIENTS IS JSON),
  CONSTRAINT BI_REPORT_SCHEDULE_STATUS_CODE_CK CHECK (STATUS_CODE IN ('ACTIVE', 'PAUSED', 'ENDED'))
);

-- -----------------------------------------------------------------------------
-- BI_EXPORT_LOG: سجل التصدير (Export Log)
