-- -----------------------------------------------------------------------------
-- OPS_INCIDENT: الحوادث التشغيلية (Operational Incidents)
-- -----------------------------------------------------------------------------
CREATE TABLE OPS_INCIDENT (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  INCIDENT_NO                      VARCHAR2(50 CHAR) NOT NULL,
  SEVERITY                         VARCHAR2(30 CHAR) NOT NULL,
  TITLE                            VARCHAR2(500 CHAR) NOT NULL,
  CELL_ID                          NUMBER(19),
  AFFECTED_TENANTS                 NUMBER(10),
  STARTED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
  DETECTED_AT                      TIMESTAMP(6) WITH LOCAL TIME ZONE,
  RESOLVED_AT                      TIMESTAMP(6) WITH LOCAL TIME ZONE,
  ROOT_CAUSE                       VARCHAR2(4000 CHAR),
  CUSTOMER_SUMMARY                 VARCHAR2(4000 CHAR),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'OPEN' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT OPS_INCIDENT_PK PRIMARY KEY (ID),
  CONSTRAINT OPS_INCIDENT_UK1 UNIQUE (INCIDENT_NO),
  CONSTRAINT OPS_INCIDENT_SEVERITY_CK CHECK (SEVERITY IN ('SEV1', 'SEV2', 'SEV3', 'SEV4')),
  CONSTRAINT OPS_INCIDENT_STATUS_CODE_CK CHECK (STATUS_CODE IN ('OPEN', 'INVESTIGATING', 'MITIGATED', 'RESOLVED', 'POSTMORTEM', 'CLOSED'))
);

-- -----------------------------------------------------------------------------
