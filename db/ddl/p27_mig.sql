SET DEFINE OFF

-- -----------------------------------------------------------------------------
-- MIG_PROJECT: مشروعات الترحيل (Migration Projects)
-- -----------------------------------------------------------------------------
CREATE TABLE MIG_PROJECT (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  CODE                             VARCHAR2(50 CHAR) NOT NULL,
  NAME_AR                          VARCHAR2(200 CHAR) NOT NULL,
  NAME_EN                          VARCHAR2(200 CHAR),
  SOURCE_SYSTEM                    VARCHAR2(200 CHAR) NOT NULL,
  COMPANY_ID                       NUMBER(19),
  CUTOVER_DATE                     DATE,
  OWNER_MEMBER_ID                  NUMBER(19),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'PLANNED' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT MIG_PROJECT_PK PRIMARY KEY (ID),
  CONSTRAINT MIG_PROJECT_UK1 UNIQUE (TENANT_ID, ID),
  CONSTRAINT MIG_PROJECT_UK2 UNIQUE (TENANT_ID, CODE),
  CONSTRAINT MIG_PROJECT_STATUS_CODE_CK CHECK (STATUS_CODE IN ('PLANNED', 'IN_PROGRESS', 'VALIDATED', 'COMPLETED', 'CANCELLED'))
);

-- -----------------------------------------------------------------------------
-- MIG_MAPPING: تعيين الحقول (Field Mappings)
-- -----------------------------------------------------------------------------
CREATE TABLE MIG_MAPPING (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  PROJECT_ID                       NUMBER(19) NOT NULL,
  TARGET_ENTITY                    VARCHAR2(50 CHAR) NOT NULL,
  VERSION_NO                       NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  MAPPING_RULES                    CLOB NOT NULL,
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'DRAFT' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT MIG_MAPPING_PK PRIMARY KEY (ID),
  CONSTRAINT MIG_MAPPING_UK1 UNIQUE (TENANT_ID, ID),
  CONSTRAINT MIG_MAPPING_UK2 UNIQUE (PROJECT_ID, TARGET_ENTITY, VERSION_NO),
  CONSTRAINT MIG_MAPPING_MAPPING_RULES_JS CHECK (MAPPING_RULES IS JSON),
  CONSTRAINT MIG_MAPPING_STATUS_CODE_CK CHECK (STATUS_CODE IN ('DRAFT', 'APPROVED'))
);

-- -----------------------------------------------------------------------------
-- MIG_BATCH: دفعات الترحيل (Migration Batches)
-- -----------------------------------------------------------------------------
CREATE TABLE MIG_BATCH (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  PROJECT_ID                       NUMBER(19) NOT NULL,
  MAPPING_ID                       NUMBER(19) NOT NULL,
  TARGET_ENTITY                    VARCHAR2(50 CHAR) NOT NULL,
  SOURCE_DOCUMENT_ID               NUMBER(19),
  IS_DRY_RUN                       CHAR(1 CHAR) DEFAULT ON NULL 'Y' NOT NULL,
  TOTAL_ROWS                       NUMBER(10),
  VALID_ROWS                       NUMBER(10),
  ERROR_ROWS                       NUMBER(10),
  LOADED_ROWS                      NUMBER(10),
  APPROVED_BY                      VARCHAR2(128 CHAR),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'UPLOADED' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT MIG_BATCH_PK PRIMARY KEY (ID),
  CONSTRAINT MIG_BATCH_UK1 UNIQUE (TENANT_ID, ID),
  CONSTRAINT MIG_BATCH_IS_DRY_RUN_CK CHECK (IS_DRY_RUN IN ('Y', 'N')),
  CONSTRAINT MIG_BATCH_STATUS_CODE_CK CHECK (STATUS_CODE IN ('UPLOADED', 'STAGED', 'VALIDATING', 'VALIDATED', 'LOADING', 'LOADED', 'RECONCILED', 'ROLLED_BACK', 'FAILED'))
);

-- -----------------------------------------------------------------------------
-- MIG_STAGING_ROW: سجلات التجهيز (Staging Rows)
-- -----------------------------------------------------------------------------
CREATE TABLE MIG_STAGING_ROW (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  BATCH_ID                         NUMBER(19) NOT NULL,
  ROW_NO                           NUMBER(10) NOT NULL,
  SOURCE_KEY                       VARCHAR2(200 CHAR),
  PAYLOAD                          CLOB NOT NULL,
  TRANSFORMED                      CLOB,
  TARGET_ID                        NUMBER(19),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'NEW' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT MIG_STAGING_ROW_PK PRIMARY KEY (ID),
  CONSTRAINT MIG_STAGING_ROW_UK1 UNIQUE (TENANT_ID, ID),
  CONSTRAINT MIG_STAGING_ROW_UK2 UNIQUE (BATCH_ID, ROW_NO),
  CONSTRAINT MIG_STAGING_ROW_PAYLOAD_JS CHECK (PAYLOAD IS JSON),
  CONSTRAINT MIG_STAGING_ROW_TRANSFORMED_JS CHECK (TRANSFORMED IS JSON),
  CONSTRAINT MIG_STAGING_ROW_STATUS_CODE_CK CHECK (STATUS_CODE IN ('NEW', 'VALID', 'INVALID', 'LOADED', 'SKIPPED'))
);

-- -----------------------------------------------------------------------------
-- MIG_ERROR: أخطاء الترحيل (Migration Errors)
-- -----------------------------------------------------------------------------
CREATE TABLE MIG_ERROR (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  STAGING_ROW_ID                   NUMBER(19) NOT NULL,
  FIELD_NAME                       VARCHAR2(128 CHAR),
  ERROR_CODE                       VARCHAR2(50 CHAR) NOT NULL,
  MESSAGE_AR                       VARCHAR2(1000 CHAR) NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  CONSTRAINT MIG_ERROR_PK PRIMARY KEY (ID)
);

-- -----------------------------------------------------------------------------
-- MIG_RECONCILIATION: مطابقة الترحيل (Migration Reconciliation)
-- -----------------------------------------------------------------------------
CREATE TABLE MIG_RECONCILIATION (
  ID                               NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TENANT_ID                        NUMBER(19) NOT NULL,
  BATCH_ID                         NUMBER(19) NOT NULL,
  CHECK_CODE                       VARCHAR2(50 CHAR) NOT NULL,
  SOURCE_VALUE                     NUMBER,
  TARGET_VALUE                     NUMBER,
  DIFFERENCE                       NUMBER,
  EXPLANATION                      VARCHAR2(1000 CHAR),
  STATUS_CODE                      VARCHAR2(30 CHAR) DEFAULT ON NULL 'MATCHED' NOT NULL,
  ROW_VERSION                      NUMBER(10) DEFAULT ON NULL 1 NOT NULL,
  CREATED_BY                       VARCHAR2(128 CHAR) NOT NULL,
  CREATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
  UPDATED_BY                       VARCHAR2(128 CHAR),
  UPDATED_AT                       TIMESTAMP(6) WITH LOCAL TIME ZONE,
  CONSTRAINT MIG_RECONCILIATION_PK PRIMARY KEY (ID),
  CONSTRAINT MIG_RECONCILIATION_STATUS_CODE_CK CHECK (STATUS_CODE IN ('MATCHED', 'DIFFERENCES', 'ACCEPTED'))
);

