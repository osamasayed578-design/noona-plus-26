DECLARE
  l_n NUMBER;
  PROCEDURE ex(p VARCHAR2) IS BEGIN EXECUTE IMMEDIATE p; EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1430, -2275, -1408, -2260, -1442, -2264, -2261) THEN RAISE; END IF; END;
  -- إضافة أعمدة إلزامية وقيود على جداول محمية بـ VPD تتطلب قراءة كامل الجدول: تعطل السياسات مؤقتاً
  PROCEDURE rls(p_on BOOLEAN) IS BEGIN
    FOR r IN (SELECT object_name, policy_name FROM user_policies WHERE object_name IN ('PAY_ELEMENT_RULE', 'PAY_EMPLOYEE_ELEMENT')) LOOP
      DBMS_RLS.ENABLE_POLICY(USER, r.object_name, r.policy_name, p_on);
    END LOOP;
  END;
BEGIN
  rls(FALSE);
  ex('ALTER TABLE PAY_ELEMENT_RULE ADD (COUNTRY_CODE VARCHAR2(2 CHAR))');
  ex(q'~ALTER TABLE PAY_ELEMENT_RULE ADD CONSTRAINT PAY_ELEMENT_RULE_COUNTRY_CODE_FK FOREIGN KEY (COUNTRY_CODE) REFERENCES REF_COUNTRY (COUNTRY_CODE)~');
  ex(q'~COMMENT ON COLUMN PAY_ELEMENT_RULE.COUNTRY_CODE IS 'الدولة (القاعدة لكل شركات المؤسسة في هذه الدولة؛ فارغ = كل الدول)'~');
  ex('ALTER TABLE PAY_ELEMENT_RULE ADD (IS_AUTO CHAR(1 CHAR) DEFAULT ON NULL ''N'' NOT NULL)');
  ex(q'~ALTER TABLE PAY_ELEMENT_RULE ADD CONSTRAINT PAY_ELEMENT_RULE_IS_AUTO_CK CHECK (IS_AUTO IN ('Y', 'N'))~');
  ex(q'~COMMENT ON COLUMN PAY_ELEMENT_RULE.IS_AUTO IS 'تطبق تلقائياً على كل موظفي النطاق (ما لم يحدد للموظف غيرها)'~');
  ex('ALTER TABLE PAY_EMPLOYEE_ELEMENT ADD (CALC_METHOD VARCHAR2(30 CHAR) DEFAULT ON NULL ''FIXED'' NOT NULL)');
  ex(q'~ALTER TABLE PAY_EMPLOYEE_ELEMENT ADD CONSTRAINT PAY_EMPLOYEE_ELEMENT_CALC_METHOD_CK CHECK (CALC_METHOD IN ('FIXED', 'PERCENT', 'POLICY', 'EXCLUDED'))~');
  ex(q'~COMMENT ON COLUMN PAY_EMPLOYEE_ELEMENT.CALC_METHOD IS 'طريقة الاحتساب: مبلغ ثابت، نسبة، حسب سياسة الشركة، مستثنى [FIXED, PERCENT, POLICY, EXCLUDED]'~');
  ex('ALTER TABLE PAY_EMPLOYEE_ELEMENT ADD (BASIS_CODE VARCHAR2(30 CHAR))');
  ex(q'~COMMENT ON COLUMN PAY_EMPLOYEE_ELEMENT.BASIS_CODE IS 'العنصر الأساس للنسبة (افتراضياً الأساسي BASIC)'~');
  rls(TRUE);
EXCEPTION WHEN OTHERS THEN
  rls(TRUE);
  RAISE;
END;
/
BEGIN
  NOONA_CORE_PKG.begin_system;
  NOONA_CORE_PKG.end_system;
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  NOONA_CORE_PKG.end_system;
  RAISE;
END;
