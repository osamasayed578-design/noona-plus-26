DECLARE
  l_n NUMBER;
  PROCEDURE ex(p VARCHAR2) IS BEGIN EXECUTE IMMEDIATE p; EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1430, -2275, -1408, -2260, -1442, -2264, -2261) THEN RAISE; END IF; END;
  -- إضافة أعمدة إلزامية وقيود على جداول محمية بـ VPD تتطلب قراءة كامل الجدول: تعطل السياسات مؤقتاً
  PROCEDURE rls(p_on BOOLEAN) IS BEGIN
    FOR r IN (SELECT object_name, policy_name FROM user_policies WHERE object_name IN ('COR_CORRESPONDENCE', 'COR_RECIPIENT')) LOOP
      DBMS_RLS.ENABLE_POLICY(USER, r.object_name, r.policy_name, p_on);
    END LOOP;
  END;
BEGIN
  rls(FALSE);
  ex('ALTER TABLE COR_CORRESPONDENCE ADD (AUTHOR_STARRED CHAR(1 CHAR) DEFAULT ON NULL ''N'' NOT NULL)');
  ex(q'~ALTER TABLE COR_CORRESPONDENCE ADD CONSTRAINT COR_CORRESPONDENCE_AUTHOR_STARRED_CK CHECK (AUTHOR_STARRED IN ('Y', 'N'))~');
  ex(q'~COMMENT ON COLUMN COR_CORRESPONDENCE.AUTHOR_STARRED IS 'مميزة بنجمة لدى المرسل'~');
  ex('ALTER TABLE COR_RECIPIENT ADD (IS_STARRED CHAR(1 CHAR) DEFAULT ON NULL ''N'' NOT NULL)');
  ex(q'~ALTER TABLE COR_RECIPIENT ADD CONSTRAINT COR_RECIPIENT_IS_STARRED_CK CHECK (IS_STARRED IN ('Y', 'N'))~');
  ex(q'~COMMENT ON COLUMN COR_RECIPIENT.IS_STARRED IS 'مميزة بنجمة لدى المستلم'~');
  rls(TRUE);
EXCEPTION WHEN OTHERS THEN
  rls(TRUE);
  RAISE;
END;
/
BEGIN
  NOONA_CORE_PKG.begin_system;
  NOONA_CORE_PKG.end_system;
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  NOONA_CORE_PKG.end_system;
  RAISE;
END;
/
