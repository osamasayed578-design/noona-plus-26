-- حالات الوصفة الجديدة: صرف خارجي، منتهية الصلاحية
DECLARE
  l_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_n FROM user_constraints WHERE table_name = 'HIS_PRESCRIPTION' AND constraint_name = 'HIS_PRESCRIPTION_STATUS_CODE_CK'
     AND search_condition_vc LIKE '%EXTERNAL%';
  IF l_n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE HIS_PRESCRIPTION DROP CONSTRAINT HIS_PRESCRIPTION_STATUS_CODE_CK';
    EXECUTE IMMEDIATE q'~ALTER TABLE HIS_PRESCRIPTION ADD CONSTRAINT HIS_PRESCRIPTION_STATUS_CODE_CK CHECK (STATUS_CODE IN ('ACTIVE', 'PARTIAL', 'DISPENSED', 'EXTERNAL', 'EXPIRED', 'CANCELLED'))~';
  END IF;
  EXECUTE IMMEDIATE q'~COMMENT ON COLUMN HIS_PRESCRIPTION.STATUS_CODE IS 'الحالة ضمن دورة الحياة المعتمدة [ACTIVE, PARTIAL, DISPENSED, EXTERNAL, EXPIRED, CANCELLED]'~';
END;
/
