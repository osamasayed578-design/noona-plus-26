DECLARE
  l_n NUMBER;
  PROCEDURE ex(p VARCHAR2) IS BEGIN EXECUTE IMMEDIATE p; EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1430, -2275, -1408, -2260, -1442, -2264, -2261) THEN RAISE; END IF; END;
  -- إضافة أعمدة إلزامية وقيود على جداول محمية بـ VPD تتطلب قراءة كامل الجدول: تعطل السياسات مؤقتاً
  PROCEDURE rls(p_on BOOLEAN) IS BEGIN
    FOR r IN (SELECT object_name, policy_name FROM user_policies WHERE object_name IN ('PRJ_COST_LINE', 'PRJ_PROGRESS_CLAIM', 'PRJ_WBS')) LOOP
      DBMS_RLS.ENABLE_POLICY(USER, r.object_name, r.policy_name, p_on);
    END LOOP;
  END;
BEGIN
  rls(FALSE);
  ex('ALTER TABLE PRJ_WBS ADD (PERCENT_COMPLETE NUMBER(9,6) DEFAULT ON NULL 0 NOT NULL)');
  ex(q'~COMMENT ON COLUMN PRJ_WBS.PERCENT_COMPLETE IS 'نسبة الإنجاز الحالية'~');
  ex('ALTER TABLE PRJ_PROGRESS_CLAIM ADD (CLAIM_KIND VARCHAR2(30 CHAR) DEFAULT ON NULL ''PROGRESS'' NOT NULL)');
  ex(q'~ALTER TABLE PRJ_PROGRESS_CLAIM ADD CONSTRAINT PRJ_PROGRESS_CLAIM_CLAIM_KIND_CK CHECK (CLAIM_KIND IN ('PROGRESS', 'ADVANCE', 'RETENTION_RELEASE'))~');
  ex(q'~COMMENT ON COLUMN PRJ_PROGRESS_CLAIM.CLAIM_KIND IS 'مستخلص أعمال، دفعة مقدمة، أو إفراج عن المحتجز [PROGRESS, ADVANCE, RETENTION_RELEASE]'~');
  ex('ALTER TABLE PRJ_COST_LINE ADD (DESCRIPTION VARCHAR2(500 CHAR))');
  ex(q'~COMMENT ON COLUMN PRJ_COST_LINE.DESCRIPTION IS 'البيان'~');
  ex('ALTER TABLE PRJ_COST_LINE ADD (REFERENCE VARCHAR2(100 CHAR))');
  ex(q'~COMMENT ON COLUMN PRJ_COST_LINE.REFERENCE IS 'المرجع'~');
  ex('ALTER TABLE PRJ_COST_LINE ADD (STATUS_CODE VARCHAR2(30 CHAR) DEFAULT ON NULL ''POSTED'' NOT NULL)');
  ex(q'~ALTER TABLE PRJ_COST_LINE ADD CONSTRAINT PRJ_COST_LINE_STATUS_CODE_CK CHECK (STATUS_CODE IN ('POSTED', 'REVERSED'))~');
  ex(q'~COMMENT ON COLUMN PRJ_COST_LINE.STATUS_CODE IS 'الحالة [POSTED, REVERSED]'~');
  rls(TRUE);
EXCEPTION WHEN OTHERS THEN
  rls(TRUE);
  RAISE;
END;
/
BEGIN
  NOONA_CORE_PKG.begin_system;
  NOONA_CORE_PKG.end_system;
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  NOONA_CORE_PKG.end_system;
  RAISE;
END;
