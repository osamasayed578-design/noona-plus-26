DECLARE
  l_n NUMBER;
  PROCEDURE ex(p VARCHAR2) IS BEGIN EXECUTE IMMEDIATE p; EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1430, -2275, -1408, -2260, -1442, -2264, -2261) THEN RAISE; END IF; END;
  -- إضافة أعمدة إلزامية وقيود على جداول محمية بـ VPD تتطلب قراءة كامل الجدول: تعطل السياسات مؤقتاً
  PROCEDURE rls(p_on BOOLEAN) IS BEGIN
    FOR r IN (SELECT object_name, policy_name FROM user_policies WHERE object_name IN ('FA_MAINTENANCE', 'TRN_MAINT_LINE', 'TRN_MAINT_ORDER')) LOOP
      DBMS_RLS.ENABLE_POLICY(USER, r.object_name, r.policy_name, p_on);
    END LOOP;
  END;
BEGIN
  rls(FALSE);
  ex('ALTER TABLE TRN_MAINT_ORDER ADD (WAREHOUSE_ID NUMBER(19))');
  ex(q'~ALTER TABLE INV_WAREHOUSE ADD CONSTRAINT INV_WAREHOUSE_TID_UK UNIQUE (TENANT_ID, ID)~');
  ex(q'~ALTER TABLE TRN_MAINT_ORDER ADD CONSTRAINT TRN_MAINT_ORDER_WAREHOUSE_ID_FK FOREIGN KEY (TENANT_ID, WAREHOUSE_ID) REFERENCES INV_WAREHOUSE (TENANT_ID, ID)~');
  ex(q'~CREATE INDEX TRN_MAINT_ORDER_WAREHOUSE_ID_IX ON TRN_MAINT_ORDER (TENANT_ID, WAREHOUSE_ID)~');
  ex(q'~COMMENT ON COLUMN TRN_MAINT_ORDER.WAREHOUSE_ID IS 'مستودع قطع الغيار والزيوت (للصرف من المخزون)'~');
  ex('ALTER TABLE TRN_MAINT_ORDER ADD (STOCK_COST NUMBER(24,6) DEFAULT ON NULL 0 NOT NULL)');
  ex(q'~COMMENT ON COLUMN TRN_MAINT_ORDER.STOCK_COST IS 'منها مصروف من المخزون'~');
  ex('ALTER TABLE TRN_MAINT_LINE ADD (FROM_STOCK CHAR(1 CHAR) DEFAULT ON NULL ''N'' NOT NULL)');
  ex(q'~ALTER TABLE TRN_MAINT_LINE ADD CONSTRAINT TRN_MAINT_LINE_FROM_STOCK_CK CHECK (FROM_STOCK IN ('Y', 'N'))~');
  ex(q'~COMMENT ON COLUMN TRN_MAINT_LINE.FROM_STOCK IS 'مصروف من المخزون'~');
  ex('ALTER TABLE TRN_MAINT_LINE ADD (INV_TXN_ID NUMBER(19))');
  ex(q'~ALTER TABLE INV_TRANSACTION ADD CONSTRAINT INV_TRANSACTION_TID_UK UNIQUE (TENANT_ID, ID)~');
  ex(q'~ALTER TABLE TRN_MAINT_LINE ADD CONSTRAINT TRN_MAINT_LINE_INV_TXN_ID_FK FOREIGN KEY (TENANT_ID, INV_TXN_ID) REFERENCES INV_TRANSACTION (TENANT_ID, ID)~');
  ex(q'~CREATE INDEX TRN_MAINT_LINE_INV_TXN_ID_IX ON TRN_MAINT_LINE (TENANT_ID, INV_TXN_ID)~');
  ex(q'~COMMENT ON COLUMN TRN_MAINT_LINE.INV_TXN_ID IS 'حركة الصرف المخزني'~');
  ex('ALTER TABLE FA_MAINTENANCE ADD (STOCK_AMOUNT NUMBER(24,6) DEFAULT ON NULL 0 NOT NULL)');
  ex(q'~COMMENT ON COLUMN FA_MAINTENANCE.STOCK_AMOUNT IS 'منها مواد مصروفة من المخزون (من حساب الصيانة تحت التنفيذ)'~');
  rls(TRUE);
EXCEPTION WHEN OTHERS THEN
  rls(TRUE);
  RAISE;
END;
